export function validateContentIntegrity(): {
  valid: boolean;
  totalLedgerEntries: number;
  inScopeEntries: number;
  excludedEntries: number;
  errors: string[];
} {
  const errors: string[] = [];
  const seenIds = new Set<string>();

  const allItems: Array<{ id: string; scope: string; excludedReason?: string }> = [
    ...CHARACTERS,
    ...WEAPONS,
    ...PASSIVES,
    ...EVOLUTIONS,
    ...ENEMIES,
    ...STAGES,
    ...RELICS,
    ...ARCANAS,
    ...SURVAROTS,
    ...POWERUPS,
    ...UNLOCKS,
    ...SECRET_SPELLS,
    ...ADVENTURES,
  ];

  let inScopeEntries = 0;
  let excludedEntries = 0;

  for (const item of allItems) {
    if (seenIds.has(item.id)) {
      errors.push(`Duplicate ledger ID: ${item.id}`);
    }
    seenIds.add(item.id);
    if (item.scope === 'dlc_excluded') {
      excludedEntries += 1;
      if (!item.excludedReason) {
        errors.push(`Excluded DLC item ${item.id} is missing excludedReason`);
      }
    } else {
      inScopeEntries += 1;
    }
  }

  for (const ch of CHARACTERS) {
    if (ch.scope === 'dlc_excluded') continue;
    if (!WEAPON_MAP[ch.startingWeaponId] || WEAPON_MAP[ch.startingWeaponId]?.scope === 'dlc_excluded') {
      errors.push(`Character ${ch.id} references invalid starting weapon ${ch.startingWeaponId}`);
    }
  }

  for (const evo of EVOLUTIONS) {
    if (!WEAPON_MAP[evo.outputWeaponId]) {
      errors.push(`Evolution ${evo.id} references missing output weapon ${evo.outputWeaponId}`);
    }
    for (const inp of evo.inputs) {
      if (!WEAPON_MAP[inp.weaponId]) {
        errors.push(`Evolution ${evo.id} references missing input weapon ${inp.weaponId}`);
      }
    }
    for (const req of evo.requiredPassives) {
      if (!PASSIVE_MAP[req.passiveId]) {
        errors.push(`Evolution ${evo.id} references missing passive ${req.passiveId}`);
      }
    }
  }

  for (const stage of STAGES) {
    if (stage.scope === 'dlc_excluded') continue;
    if (!ENEMY_MAP[stage.endBossEnemyId]) {
      errors.push(`Stage ${stage.id} references missing end boss ${stage.endBossEnemyId}`);
    }
    for (const wave of stage.waves) {
      for (const eid of wave.enemyIds) {
        if (!ENEMY_MAP[eid]) {
          errors.push(`Stage ${stage.id} wave references missing enemy ${eid}`);
        }
      }
      if (wave.bossEnemyId && !ENEMY_MAP[wave.bossEnemyId]) {
        errors.push(`Stage ${stage.id} wave references missing boss ${wave.bossEnemyId}`);
      }
    }
    for (const gi of stage.groundItems) {
      if (gi.kind === 'passive' && !PASSIVE_MAP[gi.targetId]) {
        errors.push(`Stage ${stage.id} ground item ${gi.id} references missing passive ${gi.targetId}`);
      }
      if (gi.kind === 'relic' && !RELIC_MAP[gi.targetId]) {
        errors.push(`Stage ${stage.id} ground item ${gi.id} references missing relic ${gi.targetId}`);
      }
    }
  }

  for (const adv of ADVENTURES) {
    if (adv.scope === 'dlc_excluded') continue;
    for (const cid of adv.allowedCharacterIds) {
      if (!CHARACTER_MAP[cid] || CHARACTER_MAP[cid]?.scope === 'dlc_excluded') {
        errors.push(`Adventure ${adv.id} references invalid character ${cid}`);
      }
    }
    for (const wid of adv.allowedWeaponIds) {
      if (!WEAPON_MAP[wid] || WEAPON_MAP[wid]?.scope === 'dlc_excluded') {
        errors.push(`Adventure ${adv.id} references invalid weapon ${wid}`);
      }
    }
    for (const ch of adv.chapters) {
      if (!STAGE_MAP[ch.stageId] || STAGE_MAP[ch.stageId]?.scope === 'dlc_excluded') {
        errors.push(`Adventure ${adv.id} chapter ${ch.chapterId} references invalid stage ${ch.stageId}`);
      }
    }
  }

  return {
    valid: errors.length === 0,
    totalLedgerEntries: allItems.length,
    inScopeEntries,
    excludedEntries,
    errors,
  };
}
